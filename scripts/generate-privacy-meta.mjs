import { execFileSync } from "node:child_process";
import { mkdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const privacyFile = resolve(projectRoot, "app/privacy/page.tsx");
const outputDir = resolve(projectRoot, "lib/generated");
const outputFile = resolve(outputDir, "privacy-page-meta.ts");

function gitLastCommitDate() {
  try {
    const value = execFileSync(
      "git",
      ["log", "-1", "--format=%cI", "--", "app/privacy/page.tsx"],
      {
        cwd: projectRoot,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      },
    ).trim();

    return value || null;
  } catch {
    return null;
  }
}

function gitFileIsDirty() {
  try {
    const value = execFileSync(
      "git",
      ["status", "--porcelain", "--", "app/privacy/page.tsx"],
      {
        cwd: projectRoot,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      },
    ).trim();

    return value.length > 0;
  } catch {
    // Outside a git checkout (e.g. some CI tarballs) the file mtime is the only
    // available signal.
    return true;
  }
}

function latestDate(first, second) {
  const firstTime = first ? Date.parse(first) : Number.NaN;
  const secondTime = second ? Date.parse(second) : Number.NaN;

  if (Number.isNaN(firstTime) && Number.isNaN(secondTime)) return null;
  if (Number.isNaN(firstTime)) return second;
  if (Number.isNaN(secondTime)) return first;

  return firstTime >= secondTime ? first : second;
}

const commitDate = gitLastCommitDate();
const fileModifiedAt = statSync(privacyFile).mtime.toISOString();
// A clean checkout would otherwise report the checkout time instead of the
// actual edit date, so use the commit date unless the file has local changes.
const lastModified = gitFileIsDirty()
  ? latestDate(commitDate, fileModifiedAt)
  : commitDate ?? fileModifiedAt;

if (!lastModified) {
  throw new Error("Unable to determine the privacy page last-modified date.");
}

mkdirSync(outputDir, { recursive: true });
writeFileSync(
  outputFile,
  [
    "// Generated by scripts/generate-privacy-meta.mjs. Do not edit.",
    `export const PRIVACY_PAGE_LAST_MODIFIED = ${JSON.stringify(lastModified)};`,
    "",
  ].join("\n"),
  "utf8",
);

console.log(`Privacy page metadata generated: ${lastModified}`);
